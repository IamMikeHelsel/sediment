#[test]
fn guid_text_is_mixed_endian_uppercase() {
    let efi = [0x28, 0x73, 0x2A, 0xC1, 0x1F, 0xF8, 0xD2, 0x11, 0xBA, 0x4B, 0x00, 0xA0, 0xC9, 0x3E, 0xC9, 0x3B];
    assert_eq!(format_guid(&efi), "C12A7328-F81F-11D2-BA4B-00A0C93EC93B");
    assert_eq!(format_guid(&[0; 16]), "00000000-0000-0000-0000-000000000000");
    let b: [u8; 16] = core::array::from_fn(|i| i as u8 * 17);
    assert_eq!(format_guid(&b), "33221100-5544-7766-8899-AABBCCDDEEFF");
}

#[test]
fn gpt_known_types_match_7zz() {
    for (g, name, ext) in GPT_KNOWN {
        let t = gpt_type(g);
        assert_eq!((t.name.as_str(), t.ext), (*name, *ext), "{}", format_guid(g));
    }
}

#[test]
fn gpt_unknown_types_show_guid() {
    for (g, text) in GPT_UNKNOWN {
        let t = gpt_type(g);
        assert_eq!((t.name.as_str(), t.ext), (*text, "img"));
    }
    let t = gpt_type(&[0xFF; 16]);
    assert_eq!(t.name, "FFFFFFFF-FFFF-FFFF-FFFF-FFFFFFFFFFFF");
}

#[test]
fn mbr_all_types_match_7zz() {
    for v in 1..=255u8 {
        let t = mbr_type(v);
        let want = MBR_NAMED.iter().find(|r| r.0 == v).map(|r| (r.1.to_string(), r.2)).unwrap_or((v.to_string(), "img"));
        assert_eq!((t.name, t.ext), want, "type 0x{v:02X}");
    }
    assert_eq!(mbr_type(0).name, "0");
}
