#!/usr/bin/env python3
"""Generate slt-format fixtures from real `7zz l -slt` outputs (committed in the integ repo).

Usage (from the repo root): python3 tests/gen/cli_compat_slt.py
Writes tests/fixtures/cli_compat/slt_format_fixtures/<name>.txt (the entry section, verbatim from 7zz) and
tests/fixtures/cli_compat/slt_cases.rs (an include! fragment with the matching SltEntry values).
Field values are parsed back out of the 7zz text with Python stdlib only (datetime for FILETIME).
"""
import datetime, pathlib, sys

SRC = ['tests/fixtures/sevenz/oracle/copy_solid_hc_times.slt.txt',
       'tests/fixtures/sevenz/oracle/lzma2_solid_hc.slt.txt',
       'tests/fixtures/sevenz/gen/single.slt.txt']
EPOCH = datetime.datetime(1601, 1, 1)

def filetime(s):
    date, frac = s.split('.')
    dt = datetime.datetime.strptime(date, '%Y-%m-%d %H:%M:%S')
    d = dt - EPOCH
    return (d.days * 86400 + d.seconds) * 10_000_000 + int(frac)

def attrib(s):
    letters, _, mode = s.partition(' ')
    v = 0
    for ch in letters:
        v |= {'R': 1, 'H': 2, 'S': 4, 'D': 0x10, 'A': 0x20}[ch]
    if mode:
        m = {'d': 0o040000, '-': 0o100000, 'l': 0o120000}[mode[0]]
        for i, ch in enumerate(mode[1:]):
            if ch != '-':
                m |= 1 << (8 - i)
        v |= 0x8000 | (m << 16)
    return v

def rust_str(s):
    return '"' + ''.join(c if c.isascii() and c not in '"\\' else f'\\u{{{ord(c):x}}}' for c in s) + '"'

def opt(v, f=str):
    return 'None' if v in (None, '') else f'Some({f(v)})'

def main():
    integ = pathlib.Path('.')
    tdir = integ / 'tests/fixtures/cli_compat'
    out = ['// Generated by tests/gen/cli_compat_slt.py from real 7zz -slt listings. Do not edit.',
           'fn cases() -> Vec<(&\'static str, Vec<SltEntry>)> {', '    vec![']
    for rel in SRC:
        text = (integ / rel).read_text()
        body = text.split('----------\n', 1)[1]
        name = pathlib.Path(rel).name.replace('.slt.txt', '')
        (tdir / 'slt_format_fixtures' / f'{name}.txt').write_text(body)
        out.append(f'        (include_str!("slt_format_fixtures/{name}.txt"), vec![')
        for block in body.strip('\n').split('\n\n'):
            kv = dict(line.split(' = ', 1) for line in block.split('\n'))
            f = [f'path: {rust_str(kv["Path"])}.to_string()',
                 f'size: {kv["Size"]}',
                 f'packed_size: {opt(kv["Packed Size"])}',
                 f'modified: {opt(kv.get("Modified"), lambda s: filetime(s))}',
                 f'created: {opt(kv.get("Created"), lambda s: filetime(s))}',
                 f'accessed: {opt(kv.get("Accessed"), lambda s: filetime(s))}',
                 f'attributes: {opt(kv["Attributes"], lambda s: hex(attrib(s)))}',
                 f'crc: {opt(kv["CRC"], lambda s: "0x" + s)}',
                 f'encrypted: {"true" if kv["Encrypted"] == "+" else "false"}',
                 f'method: {rust_str(kv["Method"])}.to_string()',
                 f'block: {opt(kv["Block"])}']
            out.append('            SltEntry { ' + ', '.join(f) + ', ..Default::default() },')
        out.append('        ]),')
    out += ['    ]', '}', '']
    (tdir / 'slt_cases.rs').write_text('\n'.join(out))

main()
