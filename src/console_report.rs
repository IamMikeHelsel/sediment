//! 7-Zip shaped console text for the `t`/`x`/`e`/`a`/`u`/`d` commands.
//!
//! Wrapper scripts parse 7-Zip's console output ("Everything is Ok",
//! "ERROR: CRC Failed : name", the "Files:/Size:/Compressed:" summary, the
//! open-error block), so the CLI prints the same lines in the same streams:
//! progress and summaries on standard output, `ERROR:` lines on standard
//! error. This module only formats text; `cli_run` decides when to print.
//!
//! Source: observed output of the pinned 7-Zip 26.04 `7zz` binary run
//! against a small corrupted-fixture set (good, bad CRC, truncated,
//! trailing junk, unsupported method, wrong password, not an archive); the
//! goldens live in `tests/fixtures/console/` and are regenerated by
//! `tests/gen/console_oracle.sh`. No 7-Zip source was read. The archive
//! extents used for "Tail Size" come from PKWARE APPNOTE (end of central
//! directory record) and the 7z format description (signature header).

/// Program banner, printed first unless `-ba` is given.
pub fn banner() -> String {
    format!(
        "\nSediment {} ({}) : 7-Zip compatible archiver : MIT OR Apache-2.0\n\n",
        env!("CARGO_PKG_VERSION"),
        std::env::consts::ARCH
    )
}

/// `608 bytes (1 KiB)`: the byte count plus a rounded-up unit, KiB below
/// 10 MiB, MiB below 10 GiB, then GiB. Zero has no unit part.
pub fn size_with_unit(bytes: u64) -> String {
    if bytes == 0 {
        return String::from("0 bytes");
    }
    let (shift, unit) = if bytes >= 10 << 30 {
        (30, "GiB")
    } else if bytes >= 10 << 20 {
        (20, "MiB")
    } else {
        (10, "KiB")
    };
    let rounded = bytes.div_ceil(1u64 << shift);
    format!("{bytes} bytes ({rounded} {unit})")
}

fn count(n: u64, one: &str, many: &str) -> String {
    format!("{n} {}", if n == 1 { one } else { many })
}

/// The block before an existing archive is opened by `t`/`x`/`e`.
pub fn scanning_archives_head() -> &'static str {
    "Scanning the drive for archives:\n"
}

/// The line under [`scanning_archives_head`] once the archive was read.
pub fn scanning_archives_found(files: u64, bytes: u64) -> String {
    format!("{}, {}\n", count(files, "file", "files"), size_with_unit(bytes))
}

/// `Scanning the drive:` block printed by `a`/`u` for the inputs.
pub fn scanning_drive(folders: u64, files: u64, bytes: u64) -> String {
    let mut parts = Vec::new();
    if folders > 0 {
        parts.push(count(folders, "folder", "folders"));
    }
    parts.push(count(files, "file", "files"));
    parts.push(size_with_unit(bytes));
    format!("Scanning the drive:\n{}\n\n", parts.join(", "))
}

/// What is being done to the opened archive.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Action {
    Testing,
    Extracting,
}

impl Action {
    fn verb(self) -> &'static str {
        match self {
            Action::Testing => "Testing",
            Action::Extracting => "Extracting",
        }
    }
}

/// Blank line, then `Testing archive: NAME` (or `Extracting archive:`).
pub fn action_line(action: Action, display: &str) -> String {
    format!("\n{} archive: {display}\n", action.verb())
}

/// The archive property block after a successful open: `--`, Path, Type,
/// Physical Size, then any format extras (7z: Headers Size, Method, ...).
/// `tail` is the number of bytes after the end of the archive, if any.
pub fn archive_block(display: &str, type_name: &str, physical: u64, tail: u64, extra: &[(String, String)]) -> String {
    let mut s = String::new();
    if tail > 0 {
        s.push_str(&format!("\nWARNINGS:\n{TAIL_WARNING}\n\n"));
    }
    s.push_str(&format!("--\nPath = {display}\nType = {type_name}\n"));
    if tail > 0 {
        s.push_str(&format!("WARNINGS:\n{TAIL_WARNING}\n"));
    }
    s.push_str(&format!("Physical Size = {physical}\n"));
    if tail > 0 {
        s.push_str(&format!("Tail Size = {tail}\n"));
    }
    for (k, v) in extra {
        s.push_str(&format!("{k} = {v}\n"));
    }
    s
}

/// Warning text for bytes after the end of the archive.
pub const TAIL_WARNING: &str = "There are data after the end of archive";

/// Why one member failed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EntryProblem {
    /// Checksum of the decoded data does not match.
    CrcFailed,
    /// The compressed data is damaged or truncated.
    DataError,
    /// The compression method is not supported.
    UnsupportedMethod,
    /// zip: the password does not verify.
    WrongPassword,
    /// 7z: decoding encrypted data failed.
    WrongPasswordEncrypted,
}

/// `ERROR: CRC Failed : NAME` and friends (standard error).
pub fn entry_error(problem: EntryProblem, name: &str) -> String {
    let what = match problem {
        EntryProblem::CrcFailed => "CRC Failed",
        EntryProblem::DataError => "Data Error",
        EntryProblem::UnsupportedMethod => "Unsupported Method",
        EntryProblem::WrongPassword => "Wrong password",
        EntryProblem::WrongPasswordEncrypted => "Data Error in encrypted file. Wrong password?",
    };
    format!("ERROR: {what} : {name}\n")
}

/// Totals of one finished `t`/`x`/`e`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Totals {
    pub folders: u64,
    pub files: u64,
    pub size: u64,
    pub compressed: u64,
}

/// Summary after a run without member errors. `warnings` counts archives
/// with warnings (trailing data). Printed after the blank line that
/// follows [`archive_block`] and any `-bb1` member lines.
pub fn ok_summary(t: Totals, warnings: u64) -> String {
    let mut s = String::from("Everything is Ok\n\n");
    if warnings > 0 {
        s.push_str(&format!("Archives with Warnings: {warnings}\n\nWarnings: {warnings}\n"));
    }
    s.push_str(&files_block(t));
    s
}

fn files_block(t: Totals) -> String {
    let mut s = String::new();
    if t.folders > 0 {
        s.push_str(&format!("Folders: {}\n", t.folders));
    }
    s.push_str(&format!("Files: {}\nSize:       {}\nCompressed: {}\n", t.files, t.size, t.compressed));
    s
}

/// Summary (standard output) after `errors` members failed; placed like
/// [`ok_summary`].
pub fn error_summary(errors: u64) -> String {
    format!("\nSub items Errors: {errors}\n\nArchives with Errors: 1\n\nSub items Errors: {errors}\n")
}

/// Why the archive could not be opened at all.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OpenProblem {
    /// No known format.
    NotArchive,
    /// The format was recognised but the headers are damaged.
    HeadersError,
    /// The format was recognised but the file ends early.
    UnexpectedEnd,
    /// Encrypted headers and a wrong password.
    WrongPassword,
}

/// Text for an archive that could not be opened: (standard output,
/// standard error). `type_name` is the recognised format, if any.
pub fn open_failure(display: &str, type_name: Option<&str>, problem: OpenProblem) -> (String, String) {
    let out = String::from("\nCan't open as archive: 1\nFiles: 0\nSize:       0\nCompressed: 0\n");
    let err = match (problem, type_name) {
        (OpenProblem::WrongPassword, _) => format!("ERROR: {display}\nCannot open encrypted archive. Wrong password?\n\n"),
        (OpenProblem::NotArchive, _) | (_, None) => format!("ERROR: {display}\nCannot open the file as archive\n\n"),
        (p, Some(t)) => {
            let why = if p == OpenProblem::UnexpectedEnd { "Unexpected end of archive" } else { "Headers Error" };
            format!("ERROR: {display}\n{display}\nOpen ERROR: Cannot open the file as [{t}] archive\n\n\nERRORS:\n{why}\n")
        }
    };
    (out, err)
}

/// End of the archive data for formats whose extent is recorded in the
/// file (zip: end of the EOCD record and its comment; 7z: end of the next
/// header). `None` when unknown, so no tail is reported.
pub fn archive_extent(type_name: &str, bytes: &[u8]) -> Option<u64> {
    match type_name {
        "zip" => zip_extent(bytes),
        "7z" => sevenz_extent(bytes),
        _ => None,
    }
}

fn zip_extent(b: &[u8]) -> Option<u64> {
    const SIG: [u8; 4] = [0x50, 0x4b, 0x05, 0x06];
    if b.len() < 22 {
        return None;
    }
    // Search backwards over at most 64 KiB of comment plus up to 64 KiB of
    // trailing data; take the last record whose comment fits in the file.
    let lowest = b.len().saturating_sub(22 + 0xFFFF + 0x10000);
    let mut i = b.len() - 22;
    loop {
        if b[i..i + 4] == SIG {
            let clen = u16::from_le_bytes([b[i + 20], b[i + 21]]) as usize;
            let end = i.checked_add(22)?.checked_add(clen)?;
            if end <= b.len() {
                return u64::try_from(end).ok();
            }
        }
        if i == lowest {
            return None;
        }
        i -= 1;
    }
}

fn sevenz_extent(b: &[u8]) -> Option<u64> {
    if b.len() < 32 || b[..6] != [b'7', b'z', 0xBC, 0xAF, 0x27, 0x1C] {
        return None;
    }
    let off = u64::from_le_bytes(b[12..20].try_into().ok()?);
    let size = u64::from_le_bytes(b[20..28].try_into().ok()?);
    let end = 32u64.checked_add(off)?.checked_add(size)?;
    if end <= b.len() as u64 { Some(end) } else { None }
}

/// `Creating archive: NAME` (`a`), followed by a blank line.
pub fn creating_line(display: &str) -> String {
    format!("Creating archive: {display}\n\n")
}

/// `a`: the lines after the archive was written. `items` holds the
/// `-bb1` member lines (`+ name\n`), possibly empty.
pub fn add_summary(folders: u64, files: u64, bytes: u64, items: &str, read_from_disk: u64, archive_size: u64) -> String {
    let mut what = Vec::new();
    if folders > 0 {
        what.push(count(folders, "folder", "folders"));
    }
    what.push(count(files, "file", "files"));
    what.push(size_with_unit(bytes));
    format!(
        "Add new data to archive: {}\n\n{items}\nFiles read from disk: {read_from_disk}\nArchive size: {}\nEverything is Ok\n",
        what.join(", "),
        size_with_unit(archive_size)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn units() {
        assert_eq!(size_with_unit(0), "0 bytes");
        assert_eq!(size_with_unit(1), "1 bytes (1 KiB)");
        assert_eq!(size_with_unit(1025), "1025 bytes (2 KiB)");
        assert_eq!(size_with_unit(10_240_000), "10240000 bytes (10000 KiB)");
        assert_eq!(size_with_unit(10_485_760), "10485760 bytes (10 MiB)");
        assert_eq!(size_with_unit(2_000_000_000), "2000000000 bytes (1908 MiB)");
        assert_eq!(size_with_unit(u64::MAX), format!("{} bytes (17179869184 GiB)", u64::MAX));
    }

    #[test]
    fn add_lines_match_7zz() {
        let mut s = scanning_drive(1, 2, 306);
        s.push_str(&creating_line("../ba.zip"));
        s.push_str(&add_summary(1, 2, 306, "", 2, 419));
        assert_eq!(
            s,
            "Scanning the drive:\n1 folder, 2 files, 306 bytes (1 KiB)\n\nCreating archive: ../ba.zip\n\n\
             Add new data to archive: 1 folder, 2 files, 306 bytes (1 KiB)\n\n\n\
             Files read from disk: 2\nArchive size: 419 bytes (1 KiB)\nEverything is Ok\n"
        );
    }

    #[test]
    fn extents_never_panic() {
        for n in 0..64 {
            let b = vec![0x50u8; n];
            let _ = archive_extent("zip", &b);
            let _ = archive_extent("7z", &b);
        }
        let mut z = vec![0u8; 30];
        z[8..12].copy_from_slice(&[0x50, 0x4b, 0x05, 0x06]);
        assert_eq!(archive_extent("zip", &z), Some(30));
        z[28] = 1; // comment length 1 no longer fits
        assert_eq!(archive_extent("zip", &z), None);
        let mut s = vec![b'7', b'z', 0xBC, 0xAF, 0x27, 0x1C];
        s.resize(40, 0);
        s[12] = 4;
        s[20] = 2;
        assert_eq!(archive_extent("7z", &s), Some(38));
        s[20] = 20;
        assert_eq!(archive_extent("7z", &s), None);
    }
}
